def synthesize(name, text):
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    wav = AUDIO_DIR / f"{name}.wav"
    mp3 = AUDIO_DIR / f"{name}.mp3"
    print(f"→ {name}.mp3 ({len(text)} chars)", flush=True)
    proc = subprocess.run(
        [str(PIPER), "--model", str(MODEL), "--output_file", str(wav),
         "--sentence-silence", "0.35", "--length-scale", "1.05"],
        input=text.encode("utf-8"),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr.decode("utf-8", errors="replace"))
        raise SystemExit(f"piper failed for {name}")
    subprocess.run(
        [FFMPEG, "-y", "-i", str(wav), "-codec:a", "libmp3lame", "-qscale:a", "4", str(mp3)],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    wav.unlink(missing_ok=True)
    return mp3


def main():
    if not MODEL.exists():
        raise SystemExit(f"missing model: {MODEL}")
    if not PIPER.exists():
        raise SystemExit(f"missing piper: {PIPER}")
    manifest = {}
    for name, text in TEXTS.items():
        path = synthesize(name, text)
        manifest[name] = {"file": f"audio/{name}.mp3", "chars": len(text), "bytes": path.stat().st_size}
    (AUDIO_DIR / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Done: {len(manifest)} files in {AUDIO_DIR}")


if __name__ == "__main__":
    main()
